plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.jetbrains.compose)
    alias(libs.plugins.compose.compiler)
}

group = "com.EntropicSoftwareLab.ClipboardShare"

// Linux tracks its own version, exactly as Android and Windows already do (those diverged at 3.5.1).
// v1 is LAN + clipboard only: no Wi-Fi Direct, no BLE — see LinuxPlatform.
version = "1.0.0"

layout.buildDirectory.set(file("build2"))

// Mirrors the Window Ver task: generates AppVersion.kt from `version` above so the running app can
// read its own version (the in-app update checker compares against it). Not committed.
val generatedVersionDir = layout.buildDirectory.dir("generated/kotlin/appVersion")

val generateAppVersion by tasks.registering {
    val outputDir = generatedVersionDir
    val versionValue = project.version.toString()
    inputs.property("version", versionValue)
    outputs.dir(outputDir)
    doLast {
        val pkgDir = outputDir.get().asFile.resolve("com/joseph/clipboard/linux/update")
        pkgDir.mkdirs()
        pkgDir.resolve("AppVersion.kt").writeText(
            """
            package com.joseph.clipboard.linux.update

            // Generated by the generateAppVersion Gradle task from `version` in build.gradle.kts.
            // Do not edit by hand and do not commit the generated file.
            object AppVersion {
                const val VERSION = "$versionValue"
            }
            """.trimIndent() + "\n"
        )
    }
}

kotlin {
    jvmToolchain(17)
    sourceSets.main {
        kotlin.srcDir(generatedVersionDir)
    }
}

tasks.named("compileKotlin") {
    dependsOn(generateAppVersion)
}

dependencies {
    implementation(project(":desktop-core"))
    testImplementation(libs.junit)
}

compose.desktop {
    application {
        mainClass = "com.joseph.clipboard.linux.MainKt"
        System.getenv("JAVA_HOME")?.let { javaHome = it }
        nativeDistributions {
            // Deb is the actual Linux installer target. Note that TargetFormat.AppImage is NOT the
            // Linux AppImage format — in Compose's DSL it maps to jpackage's `app-image`, the
            // unpackaged runtime directory that createDistributable produces. Both are only
            // buildable ON Linux: jpackage never cross-builds, so a Linux artifact can never come
            // out of the Windows dev machine and CI is the build machine for this module.
            targetFormats(
                org.jetbrains.compose.desktop.application.dsl.TargetFormat.Deb,
                org.jetbrains.compose.desktop.application.dsl.TargetFormat.AppImage,
            )
            packageName = "offbridge"
            packageVersion = "1.0.0"
            description = "Off-grid file transfer and clipboard sync between Linux and Android"
            vendor = "EntropicSoftwareLab"
            linux {
                menuGroup = "Network"
                appCategory = "Network"
                iconFile.set(project.file("src/main/resources/linux/app-256.png"))
            }
        }
        buildTypes.release.proguard {
            isEnabled.set(false)
        }
    }
}
