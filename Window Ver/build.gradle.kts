plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.jetbrains.compose)
    alias(libs.plugins.compose.compiler)
}

group = "com.EntropicSoftwareLab.ClipboardShare"
version = "3.7.10"

layout.buildDirectory.set(file("build2"))

// Generates AppVersion.kt from the project `version` above, so the running app can read its own
// version at runtime (previously only build.gradle.kts/packageVersion/the .iss knew it — nothing
// shipped in the jar did). Feeds the in-app update checker's version comparison.
val generatedVersionDir = layout.buildDirectory.dir("generated/kotlin/appVersion")

val generateAppVersion by tasks.registering {
    val outputDir = generatedVersionDir
    val versionValue = project.version.toString()
    inputs.property("version", versionValue)
    outputs.dir(outputDir)
    doLast {
        val pkgDir = outputDir.get().asFile.resolve("com/joseph/clipboard/windows/update")
        pkgDir.mkdirs()
        pkgDir.resolve("AppVersion.kt").writeText(
            """
            package com.joseph.clipboard.windows.update

            // Generated by the generateAppVersion Gradle task from `version` in build.gradle.kts.
            // Do not edit by hand and do not commit the generated file.
            object AppVersion {
                const val VERSION = "$versionValue"
            }
            """.trimIndent() + "\n"
        )
    }
}

kotlin {
    jvmToolchain(17)
    sourceSets.main {
        kotlin.srcDir(generatedVersionDir)
    }
}

tasks.named("compileKotlin") {
    dependsOn(generateAppVersion)
}

dependencies {
    // The portable ~94% of this client. Compose, gson and zxing arrive transitively as `api`
    // dependencies of core, so they are deliberately not re-declared here.
    implementation(project(":desktop-core"))

    // Windows DPAPI (Crypt32) for encrypting pairing keys at rest in config.json, plus the Kernel32
    // named mutex the Inno installer checks before an in-place upgrade. Windows-only, and scoped to
    // this module on purpose so the Linux artifact never ships Win32 bindings.
    implementation(libs.jna.platform)

    testImplementation(libs.junit)
}

compose.desktop {
    application {
        mainClass = "com.joseph.clipboard.windows.MainKt"
        System.getenv("JAVA_HOME")?.let { javaHome = it }
        nativeDistributions {
            targetFormats(org.jetbrains.compose.desktop.application.dsl.TargetFormat.AppImage, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Exe, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Msi)
            packageName = "OffBridge"
            packageVersion = "3.7.10"
            description = "Off-grid file transfer and clipboard sync between Windows and Android"
            vendor = "EntropicSoftwareLab" // must match the Inno installer's MyAppPublisher
            windows {
                menu = true
                shortcut = true
                menuGroup = "OffBridge"
                perUserInstall = true
                dirChooser = true
                upgradeUuid = "12255bbe-e53b-408b-8866-27ab965d1394"
                // Brand icon for the launcher exe and the Start Menu/desktop shortcuts. The same
                // app.ico is reused by the Inno installer (SetupIconFile) so the setup .exe and the
                // installed app share one icon. Regenerate it with installer/make-brand-assets.ps1.
                iconFile.set(project.file("src/main/resources/windows/app.ico"))
            }
        }
        buildTypes.release.proguard {
            isEnabled.set(false)
        }
    }
}

afterEvaluate {
    tasks.named("packageMsi") {
        doFirst {
            val resourcesDir = file("${layout.buildDirectory.get()}/compose/tmp/resources")
            resourcesDir.mkdirs()
            file("src/main/resources/windows/main.wxs").copyTo(file("${resourcesDir.absolutePath}/main.wxs"), overwrite = true)
            file("src/main/resources/windows/License.rtf").copyTo(file("${resourcesDir.absolutePath}/License.rtf"), overwrite = true)
        }
    }
}
